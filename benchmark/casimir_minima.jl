# Local minima of C₂(r₁) + C₂(r₂) over pairs with r₂ ⊂ r₁ ⊗ R.
#
#   julia --project -t auto benchmark/casimir_minima.jl [output_dir [cosh_cache]]
#
# For each real irrep r of `cosh_table.jl`, R is the representation with
# character 2^{m₀} ∏_{w∈Φ⁺(r)} (e^{w/2} + e^{-w/2}) (only its set of irreducible
# components matters here).  A pair (r₁, r₂) with r₂ ⊂ r₁ ⊗ R is a local minimum
# if neither C₂(r₁) nor C₂(r₂) can be lowered by changing that entry alone while
# keeping r₂ ⊂ r₁ ⊗ R.
#
# Method.  R is self-conjugate, so r₂ ⊂ r₁ ⊗ R ⇔ r₁ ⊂ r₂ ⊗ R and the problem is
# symmetric.  Let m(λ) be the set of irreps of minimal C₂ in λ ⊗ R and
# s(λ) = min C₂(λ ⊗ R) − C₂(λ).  Then (a, b) is a local minimum iff b ∈ m(a) and
# a ∈ m(b), which forces s(a) + s(b) = 0, so s(a) ≥ 0 or s(b) ≥ 0.  We enumerate
# all dominant λ with C₂(λ) ≤ B, collect S₀ = {λ : s(λ) ≥ 0}, and for a ∈ S₀ test
# every b ∈ m(a).  B is doubled until every element of S₀ has C₂ ≤ B/2, and the
# outer shell is reported, so the search is complete up to the stated cutoff.
#
# Minimal-C₂ components of λ ⊗ ν are found with the Racah–Speiser algorithm; the
# components ν of R are scanned in order of |ν + ρ| and skipped as soon as the
# bound |κ + ρ| ≥ |ν + ρ| − |λ| (κ any component of λ ⊗ ν) shows they cannot
# beat the current minimum.
using Kiwi
using Printf
using Serialization
using LinearAlgebra

const K = Kiwi
include(joinpath(@__DIR__, "cosh_table.jl"))   # CASES, LEVI, run_case

struct MinData
    g::LieAlgebra
    ad::K.AlgebraData
    comps::Vector{Vector{Int}}      # components of R, sorted by |ν + ρ|
    normρ::Vector{Float64}          # |ν + ρ|
    negcache::Dict{Vector{Int}, Vector{Tuple{Vector{Int}, Int}}}
end

function MinData(R::Rep)
    g = R.algebra
    ad = K.algebra_data(g)
    comps = [ir.dynkin_labels for ir in keys(R.components)]
    nr(v) = sqrt(dot(v .+ 1, ad.G * (v .+ 1)) / ad.Gden)
    sort!(comps, by = nr)
    MinData(g, ad, comps, nr.(comps), Dict{Vector{Int}, Vector{Tuple{Vector{Int}, Int}}}())
end

# 2·Gden·C₂(λ) as an exact integer
c2(ad, λ) = dot(λ, ad.G * (λ .+ 2))
c2float(ad, λ) = c2(ad, λ) / (2ad.Gden)

"""
    minset(md, λ) -> (2Gden·min C₂, minimisers)

Irreps of minimal quadratic Casimir in λ ⊗ R.

A Racah–Speiser term `ν + ρ + μ` (μ a weight of λ) contributes the irrep κ with
`|κ + ρ| = |ν + ρ + μ|` because Weyl reflections preserve norms, so
`2·C₂(κ) = |ν+ρ+μ|² − |ρ|²` and terms can only cancel against terms of equal
norm.  On a Weyl orbit `|ν+ρ+μ|²` increases monotonically as μ moves up from the
lowest weight, so the terms of norm ≤ T are generated by walking each orbit of
weights of λ upwards from its lowest weight and pruning; T is raised until a
level with positive net multiplicity appears.
"""
function minset(md::MinData, λ::Vector{Int})
    ad = md.ad
    n = ad.n
    # weights of the smaller factor, as orbits walked from their lowest weight
    negsof(κ) = get!(md.negcache, κ) do
        doms, mults = dominant_character(md.g, κ)
        [((x = -d; K._reflect_to_dominant!(x, ad); x), m) for (d, m) in zip(doms, mults)]
    end
    nλ = sqrt(dot(λ, ad.G * λ) / ad.Gden)
    ρρ = ad.ρρ
    nrm2(v) = dot(v, ad.G * v)                     # Gden·|v|²; Gden·2C₂(κ) = nrm2(κ+ρ) - ρρ
    best = typemax(Int)
    arg = Vector{Vector{Int}}()
    for (ν, nν) in zip(md.comps, md.normρ)
        # |κ+ρ| ≥ |ν+ρ| - |λ| for every component κ of λ ⊗ ν; comps sorted by |ν+ρ|
        max(nν - nλ, 0.0)^2 * ad.Gden - ρρ > best + 1e-6 && break
        # Racah–Speiser with the larger highest weight as the base
        big, small = nrm2(ν) >= nrm2(λ) ? (ν, λ) : (λ, ν)
        negs = negsof(small)
        νρ = big .+ 1
        lb = minimum(nrm2(νρ .- x) for (x, _) in negs)
        lb - ρρ > best && continue
        T = lb
        step = 4ad.Gden
        while true
            net = Dict{Vector{Int}, Int}()
            for (x0, m) in negs
                layer = [x0]
                while !isempty(layer)
                    next = Vector{Vector{Int}}()
                    seen = Set{Vector{Int}}()
                    for x in layer
                        z = νρ .- x
                        nrm2(z) <= T || continue       # everything above is larger
                        s = K._rs_reflect!(z, ad)
                        if s != 0
                            κ = z .- 1
                            net[κ] = get(net, κ, 0) + s * m
                        end
                        for i in 1:n
                            c = x[i]
                            c > 0 || continue
                            y = x .- c .* view(ad.α, :, i)
                            y in seen || (push!(seen, y); push!(next, y))
                        end
                    end
                    layer = next
                end
            end
            pos = [κ for (κ, c) in net if c > 0]
            if !isempty(pos)
                v = minimum(κ -> c2(ad, κ), pos)
                if v < best
                    best = v
                    empty!(arg)
                end
                if v == best
                    for κ in pos
                        c2(ad, κ) == v && !(κ in arg) && push!(arg, κ)
                    end
                end
                break
            end
            T - ρρ > best && break                   # cannot beat the current minimum
            T += step
            step *= 2
        end
    end
    return best, arg
end

# Dominant weights with 2Gden·C₂ ≤ bound (C₂ increases with every label)
function dominant_below(ad, bound)
    n = ad.n
    out = [zeros(Int, n)]
    seen = Set(out)
    k = 1
    while k <= length(out)
        λ = out[k]
        for i in 1:n
            μ = copy(λ); μ[i] += 1
            (μ in seen || c2(ad, μ) > bound) && continue
            push!(seen, μ); push!(out, μ)
        end
        k += 1
    end
    return out
end

function local_minima(R::Rep; B0 = nothing, maxB = Inf)
    md = MinData(R)
    ad = md.ad
    cache = Dict{Vector{Int}, Tuple{Int, Vector{Vector{Int}}}}()
    m(λ) = get!(() -> minset(md, λ), cache, λ)
    # initial cutoff (doubled until the stopping criterion holds)
    B = B0 === nothing ? 8ad.Gden : B0
    S0 = Vector{Vector{Int}}()
    nscanned = 0
    while true
        λs = dominant_below(ad, B)
        nscanned = length(λs)
        S0 = [λ for λ in λs if m(λ)[1] >= c2(ad, λ)]
        maxS0 = maximum(c2(ad, λ) for λ in S0)
        (2maxS0 <= B || 2B > maxB) && break
        B *= 2
    end
    pairs = Set{Tuple{Vector{Int}, Vector{Int}}}()
    for a in S0, b in m(a)[2]
        if a in m(b)[2]
            push!(pairs, (a, b)); push!(pairs, (b, a))
        end
    end
    sorted = sort!(collect(pairs), by = p -> (c2(ad, p[1]) + c2(ad, p[2]), p))
    return (pairs = sorted, B = B / (2ad.Gden), nscanned = nscanned, S0 = S0,
            ncomps = length(md.comps))
end

fmt(λ) = "[" * join(λ, ",") * "]"

function main(outdir, cachefile)
    cache = isfile(cachefile) ? deserialize(cachefile) : Dict()
    io = open(joinpath(outdir, "casimir_minima.md"), "w")
    println(io, "# Local minima of C₂(r₁) + C₂(r₂) with r₂ ⊂ r₁ ⊗ R\n")
    println(io, "R is the representation of `cosh_product_table.md`. A pair is a local minimum if ",
                "neither C₂(r₁) nor C₂(r₂) can be lowered by changing that entry alone while keeping ",
                "r₂ ⊂ r₁ ⊗ R. C₂ is normalised as (λ, λ+2ρ)/2 with long roots of length² 2 ",
                "(C₂ of the SU(2) spin-j irrep is j(j+1)/2). Pairs are listed with C₂(r₁) + C₂(r₂); ",
                "each unordered pair {r₁, r₂} is shown once (both orders are minima). ",
                "Search cutoff: every r₁ with C₂(r₁) ≤ B was examined; all candidates found have ",
                "C₂ ≤ B/2.\n")
    summary = []
    for (g, l) in CASES
        key = (string(g), l)
        res = haskey(cache, key) ? cache[key] : run_case(g, l)
        t = @elapsed lm = local_minima(res.R)
        ad = K.algebra_data(g)
        unordered = [(a, b) for (a, b) in lm.pairs if a <= b]
        @printf("%-5s %-22s comps=%-6d B=%-8.2f scanned=%-6d minima=%-4d %.2fs\n", string(g), fmt(l),
                lm.ncomps, lm.B, lm.nscanned, length(unordered), t)
        flush(stdout)
        push!(summary, (g, l, lm, t))
        println(io, "## ", g, " r = ", fmt(l), " (dim ", dimension(Irrep(g, l)), ")\n")
        println(io, "R has $(lm.ncomps) distinct components; cutoff B = $(round(lm.B, digits = 2)) ",
                    "($(lm.nscanned) irreps r₁ scanned); $(length(unordered)) local minima; ",
                    "$(round(t, digits = 2)) s.\n")
        vals = sort(unique(c2(ad, a) + c2(ad, b) for (a, b) in unordered))
        for v in vals
            ps = [(a, b) for (a, b) in unordered if c2(ad, a) + c2(ad, b) == v]
            str = join(["(" * fmt(a) * ", " * fmt(b) * ")" for (a, b) in ps], ", ")
            println(io, "* C₂ sum = ", v // (2ad.Gden), ": ", str)
        end
        println(io)
        flush(io)
    end
    close(io)
end

if abspath(PROGRAM_FILE) == @__FILE__
    main(length(ARGS) >= 1 ? ARGS[1] : @__DIR__, length(ARGS) >= 2 ? ARGS[2] : "")
end
